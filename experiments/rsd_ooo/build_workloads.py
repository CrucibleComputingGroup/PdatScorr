#!/usr/bin/env python3
"""Build deterministic bare-metal memory kernels; never touches upstream RTL.

These are diagnostic workloads, not application-suite results. The region-safe
kernels load only ROM and store only RAM/MMIO, including startup (no stack).
The alias kernel deliberately violates that contract and is a negative control.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent
MASK = (1 << 32) - 1
MODES = ('stream_sum', 'stream_mix', 'pointer_chase', 'alias_feedback')


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def generate(mode, seed, count):
    values = []
    state = seed
    for _ in range(2 * count):
        state = (1664525 * state + 1013904223) & MASK
        values.append(state)
    a, b = values[:count], values[count:]
    if mode == 'stream_sum':
        expected = sum((x + y) & MASK for x, y in zip(a, b)) & MASK
        body = 'lw t0, 0(s0)\nlw t1, 0(s1)\nadd t2, t0, t1'
    elif mode == 'stream_mix':
        expected = sum(((x + 3*y) & MASK) ^ (((x << 5) | (x >> 27)) & MASK)
                       for x, y in zip(a, b)) & MASK
        body = ('lw t0, 0(s0)\nlw t1, 0(s1)\nslli t2, t1, 1\nadd t2, t2, t1\n'
                'add t2, t2, t0\nslli t3, t0, 5\nsrli t4, t0, 27\n'
                'or t3, t3, t4\nxor t2, t2, t3')
    elif mode == 'pointer_chase':
        # A single cycle over a power-of-two table, with a dependent next load.
        stride = (seed * 2 + 1) & (count - 1)
        a = [0x8000 + 4 * ((i + stride) & (count - 1)) for i in range(count)]
        pos = 0
        expected = 0
        for _ in range(count):
            expected = (expected + a[pos]) & MASK
            pos = (pos + stride) & (count - 1)
        body = 'lw t2, 0(s0)\nmv s0, t2'
    else:
        # Dependency on the preceding store: a cut that ignores aliasing fails.
        expected = sum((seed + i + 1) & MASK for i in range(count)) & MASK
        body = 'lw t0, 0(s2)\naddi t2, t0, 1\nsw t2, 0(s2)'

    initial = f'li t0, {seed}\nsw t0, 0(s2)\n' if mode == 'alias_feedback' else ''
    advance = '' if mode in ('pointer_chase', 'alias_feedback') else 'addi s0, s0, 4\n'
    stores = '' if mode == 'alias_feedback' else 'sw t2, 0(s2)\naddi s2, s2, 4\n'
    serial_prefix = ''.join(f'li t0, {ord(c)}\nsb t0, 0(s5)\n' for c in 'signature=')
    source = f'''# Generated by build_workloads.py. Input seed={seed}, mode={mode}.
.option norelax
.option norvc
.section .text
.globl _start
_start:
  j init
_end:
  j _end
init:
  la t0, trap
  csrw mtvec, t0
  li s0, 0x8000
  li s1, {0x8000 + 4*count}
  li s2, 0x80004000
  li s3, {count}
  li s4, 0
  {initial}
.globl roi_begin
roi_begin:
  {body}
  {stores}
  add s4, s4, t2
  {advance}
  addi s1, s1, 4
  addi s3, s3, -1
  bnez s3, roi_begin
.globl roi_end
roi_end:
  li s5, 0x40002000
  {serial_prefix}
  li t3, 28
print_hex:
  srl t0, s4, t3
  andi t0, t0, 15
  li t1, 10
  bltu t0, t1, digit
  addi t0, t0, 87
  j output
digit:
  addi t0, t0, 48
output:
  sb t0, 0(s5)
  addi t3, t3, -4
  bgez t3, print_hex
  li t0, 10
  sb t0, 0(s5)
  fence rw, rw
  j _end
trap:
  li t0, 0x40002000
  li t1, 33
  sb t1, 0(t0)
trap_loop:
  j trap_loop
.section .rodata
.balign 4
inputs:
'''
    source += '\n'.join(f'.word 0x{x:08x}' for x in a + b) + '\n'
    return source, expected


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--prefix', default='/home/allenjin/riscv/bin/riscv32-unknown-elf-')
    p.add_argument('--seeds', nargs='+', type=int, default=[1, 7, 42])
    p.add_argument('--count', type=int, default=512)
    p.add_argument('--output', type=Path, default=ROOT / 'workloads')
    args = p.parse_args()
    if args.count < 4 or args.count > 2048 or args.count & (args.count - 1):
        p.error('count must be a power of two in [4, 2048]')
    env = dict(os.environ, PATH='/usr/bin:/bin:/usr/local/bin')
    args.output.mkdir(parents=True, exist_ok=True)
    compiler = subprocess.check_output([args.prefix + 'gcc', '--version'], text=True, env=env).splitlines()[0]
    rows = []
    for mode in MODES:
        for seed in args.seeds:
            out = args.output / f'{mode}_s{seed}_n{args.count}'
            out.mkdir(exist_ok=True)
            source, expected = generate(mode, seed, args.count)
            (out / 'code.S').write_text(source)
            (out / 'link.ld').write_text('OUTPUT_ARCH(riscv)\nENTRY(_start)\nSECTIONS {\n'
                ' .text 0x1000 : { *(.text) }\n .rodata 0x8000 : { *(.rodata) }\n}\n')
            commands = [
                [args.prefix + 'gcc', '-march=rv32im_zicsr', '-mabi=ilp32', '-nostdlib',
                 '-nostartfiles', '-Wl,--no-relax', '-T', str(out / 'link.ld'),
                 str(out / 'code.S'), '-o', str(out / 'code.elf')],
                [args.prefix + 'objcopy', '-O', 'binary', str(out / 'code.elf'), str(out / 'code.rom.bin')],
            ]
            for cmd in commands:
                subprocess.run(cmd, check=True, env=env, capture_output=True)
            dump = subprocess.check_output([args.prefix+'objdump', '-d', str(out/'code.elf')], env=env)
            (out / 'code.dump').write_bytes(dump)
            data = bytes(4096) + (out / 'code.rom.bin').read_bytes()
            if len(data) > 65536:
                raise RuntimeError('ROM image exceeds input memory range')
            data = data.ljust(65536, b'\0')
            (out / 'code.hex').write_text(''.join(data[i:i+16][::-1].hex()+'\n' for i in range(0,len(data),16)))
            row = dict(name=out.name, mode=mode, seed=seed, count=args.count,
                       expected_serial=f'signature={expected:08x}\n',
                       region_contract=mode != 'alias_feedback',
                       compiler=compiler, commands=commands,
                       hashes={f:sha(out/f) for f in ('code.S','code.elf','code.hex','link.ld')})
            (out/'manifest.json').write_text(json.dumps(row, indent=2)+'\n')
            rows.append(row)
    (args.output/'manifest.json').write_text(json.dumps(rows, indent=2)+'\n')
    print(json.dumps({'workloads':len(rows), 'output':str(args.output), 'compiler':compiler}))


if __name__ == '__main__':
    main()
