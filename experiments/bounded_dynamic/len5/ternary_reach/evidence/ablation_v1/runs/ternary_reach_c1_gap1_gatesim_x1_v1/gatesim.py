#!/usr/bin/env python3
"""Gate-level co-simulation of mapped substituted cores against the original core RTL.

Each mapped netlist (map_netlist.py: the netlist whose cell area is reported) runs
with behavioral models of its SKY130 cells, generated by Yosys from the liberty
file used for mapping, in its own copy of the closed platform harness next to the
original core RTL, under the stimuli of cosim.py. Every cycle from the first reset
on, the testbench checks that the certified constants hold in the original core,
that the platform assertions hold, and that each netlist certified for this
platform matches the original on every core output. Netlists certified only for
other platforms run as negative controls. Internal state is not compared: the
netlist has no flip-flop correspondence with the RTL.

All storage starts at zero, because the netlist's flip-flops without reset cannot be
paired with the original's by name; harness registers start from the same random
value in every copy. Synthesis has resolved the explicit X constants of the RTL;
the original core's X constants take the value given by --x-assign.

This is finite simulation evidence. It does not replace the ternary invariant.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import csv
import json
import os
from pathlib import Path
import random
import re
import shutil
import subprocess
import sys
import time

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(HERE))
from odc.temporal import checked_yosys, digest, export_design, yosys_path  # noqa: E402
from export_closed import flip_flop_manifest, observed_design  # noqa: E402
from cosim import (INSTANCE, PROBES, TESTBENCH, data_image, fill, hex_vector, parse_result,  # noqa: E402
                   replace_once, seed_no_reset_flip_flops, sim_platform)
from map_netlist import TOP  # noqa: E402
from prepare_frontend import workspace_root  # noqa: E402

CHECK = r"""    if (v@I@_core != o_core) begin
      mism[@I@]++;
      if (first_mism[@I@] < 0) begin
        first_mism[@I@] = cyc;
        report_bits("mism", @I@, '0, v@I@_core ^ o_core);
      end
    end
"""
IDENT = r"[A-Za-z_][A-Za-z0-9_]*"


def netlist_ports(text: str) -> dict[str, tuple[str, int]]:
    if len(re.findall(r"(?m)^module ", text)) != 1:
        raise ValueError("Mapped netlist must contain exactly one module")
    body = re.search(rf"(?ms)^module {TOP}\(.*?\);\n(.*?)^endmodule", text)
    if body is None:
        raise ValueError(f"Mapped netlist has no module {TOP}")
    ports = {}
    for m in re.finditer(rf"(?m)^  (input|output|inout) (?:\[(\d+):(\d+)\] )?({IDENT});$", body.group(1)):
        width = int(m.group(2)) - int(m.group(3)) + 1 if m.group(2) else 1
        ports[m.group(4)] = (m.group(1), width)
    return ports


def cell_models(yosys: str, liberty: Path, types: set[str], out: Path, timeout: int) -> Path:
    checked_yosys(yosys, "read_liberty -ignore_miss_func -ignore_miss_dir -ignore_miss_data_latch "
                  f"{yosys_path(liberty)}\nwrite_verilog -noattr {yosys_path(out / 'cells_all.v')}\n",
                  out, "cells", timeout)
    modules = {m.group(1): m.group(0) for m in
               re.finditer(rf"(?ms)^module ({IDENT})\(.*?^endmodule\n", (out / "cells_all.v").read_text())}
    missing = sorted(types - set(modules))
    if missing:
        raise ValueError(f"No behavioral model for cells {missing}")
    path = out / "cells.v"
    path.write_text("// Generated by Yosys read_liberty from the mapping liberty; used cells only.\n"
                    + "".join(modules[t] for t in sorted(types)))
    return path


def wrapper(name: str, ports: dict) -> str:
    """A core with the observed core's ports: the netlist, with observation outputs tied to zero."""
    decls, conns, ties = [], [], []
    for port, p in sorted(ports.items()):
        width = len(p["bits"])
        decls.append(f"  {p['direction']} wire {f'[{width - 1}:0] ' if width > 1 else ''}{port}")
        if port in PROBES:
            ties.append(f"  assign {port} = '0;\n")
        else:
            conns.append(f".{port}({port})")
    return (f"module Gate_{name}(\n" + ",\n".join(decls) + ");\n"
            f"  {TOP}_{name} netlist({', '.join(conns)});\n" + "".join(ties) + "endmodule\n")


def main() -> int:
    workspace = workspace_root(HERE)
    bin_dir = workspace / "tools/oss-cad-suite-20261104/oss-cad-suite/bin"
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--model", type=Path, required=True, help="export_closed.py output (the platform)")
    ap.add_argument("--reach", type=Path, required=True, help="reach.py output for this model")
    ap.add_argument("--netlist", action="append", required=True, metavar="NAME=MAP_NETLIST_DIR")
    ap.add_argument("--evidence", type=Path, required=True, help="Recorded RTL platform simulation evidence")
    ap.add_argument("--output", type=Path, required=True)
    ap.add_argument("--seeds", type=int, default=16)
    ap.add_argument("--cycles", type=int, default=20000)
    ap.add_argument("--reset-periods", type=int, nargs="+", default=[300, 1000, 3000, 0])
    ap.add_argument("--image-seeds", type=int, default=2)
    ap.add_argument("--x-assign", choices=("0", "1"), default="0")
    ap.add_argument("--yosys", default=str(bin_dir / "yosys"))
    ap.add_argument("--verilator", default=str(bin_dir / "verilator"))
    ap.add_argument("--jobs", type=int, default=min(64, os.cpu_count() or 1))
    ap.add_argument("--timeout", type=int, default=7200)
    args = ap.parse_args()
    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=False)
    for helper in ("gatesim.py", "cosim.py", "map_netlist.py"):
        shutil.copyfile(HERE / helper, out / helper)
    model = args.model.resolve()
    summary = json.loads((model / "summary.json").read_text())
    if summary.get("status") != "exported" or digest(model / "ClosedPlatform.sv") != summary["platform_sha256"]:
        raise ValueError("Model directory does not match its export record")
    reach = json.loads((args.reach / "summary.json").read_text())
    constants = json.loads((args.reach / "constants.json").read_text())
    if reach.get("status") != "certified" or reach["model_aig_sha256"] != summary["aig_sha256"] \
            or constants["status"] != "certified" or digest(args.reach / "constants.json") != reach["constants_sha256"]:
        raise ValueError("Reachability result is not a certified run of this model")
    if digest(args.evidence / "instruction.hex") != digest(model / "program.hex"):
        raise ValueError("Evidence program differs from the model ROM image")
    design_path = Path(summary["design"])
    if digest(design_path) != summary["design_sha256"]:
        raise ValueError("Original design changed since export")
    original = json.loads(design_path.read_text())
    records = flip_flop_manifest(original)
    if [(r["cell"], r["bit"], r["net"]) for r in records] != \
            [(r["cell"], r["bit"], r["net"]) for r in json.loads((model / "manifest.json").read_text())["records"]]:
        raise ValueError("Flip-flop manifest differs from the model")
    index = {(r["cell"], r["bit"]): i for i, r in enumerate(records)}
    mask, value = [0] * len(records), [0] * len(records)
    for c in constants["constants"]:
        i = index[(c["cell"], c["bit"])]
        mask[i], value[i] = 1, c["value"]

    observed = observed_design(original, records)
    ports = observed["modules"]["datapath"]["ports"]
    outputs = sorted((n, len(p["bits"])) for n, p in ports.items() if p["direction"] == "output" and n not in PROBES)
    expected_ports = {n: (p["direction"], len(p["bits"])) for n, p in ports.items() if n not in PROBES}
    platform_text = (model / "ClosedPlatform.sv").read_text()
    verilog = out / "core_orig.v"
    export_design(observed, "datapath", "Core_orig", verilog, args.yosys, args.timeout)
    if digest(verilog.with_suffix(".json")) != summary["core_json_sha256"]:
        raise ValueError("Original observed core differs from the formal model's core")
    text, _ = seed_no_reset_flip_flops(verilog.read_text(), records)
    (out / "sim_core_orig.v").write_text(text)
    ptext, platform_info = sim_platform(platform_text, "orig", "Core_orig", outputs)
    (out / "platform_orig.sv").write_text(ptext)
    files = [out / "sim_core_orig.v", out / "platform_orig.sv"]

    netlists, liberty, cell_types = [], None, set()
    for spec in args.netlist:
        name, _, path = spec.partition("=")
        if not re.fullmatch(r"[a-z][a-z0-9]*", name) or name == "orig" or not path:
            ap.error(f"Bad --netlist {spec}")
        ndir = Path(path).resolve()
        nsum = json.loads((ndir / "summary.json").read_text())
        if nsum.get("status") != "mapped" or digest(ndir / "mapped.v") != nsum["netlist_sha256"] or nsum["top"] != TOP:
            raise ValueError(f"{ndir} is not a reproduced map run")
        ssum = json.loads((Path(nsum["substitute"]) / "summary.json").read_text())
        if digest(Path(nsum["substitute"]) / "summary.json") != nsum["substitute_summary_sha256"] \
                or ssum["design_sha256"] != summary["design_sha256"]:
            raise ValueError(f"{name}: netlist is not mapped from a substitution of this design")
        if liberty is None:
            liberty = Path(nsum["liberty"])
        if Path(nsum["liberty"]) != liberty or digest(liberty) != nsum["liberty_sha256"]:
            raise ValueError("Netlists use different liberty files")
        mapped = (ndir / "mapped.v").read_text()
        found = netlist_ports(mapped)
        if found != expected_ports:
            raise ValueError(f"{name}: netlist ports differ from the core ports")
        types = set(re.findall(r"(?m)^  (sky130_fd_sc_hd__\w+) ", mapped))
        instances = len(re.findall(r"(?m)^  sky130_fd_sc_hd__\w+ ", mapped))
        if types != set(nsum["cell_types"]) or instances != nsum["cells"]:
            raise ValueError(f"{name}: netlist cell instances differ from the area report")
        cell_types |= types
        (out / f"netlist_{name}.v").write_text(replace_once(mapped, f"module {TOP}(", f"module {TOP}_{name}("))
        (out / f"gate_{name}.v").write_text(wrapper(name, ports))
        ptext, info = sim_platform(platform_text, name, f"Gate_{name}", outputs)
        if info != platform_info:
            raise ValueError("Platform copies differ")
        (out / f"platform_{name}.sv").write_text(ptext)
        files += [out / f"netlist_{name}.v", out / f"gate_{name}.v", out / f"platform_{name}.sv"]
        certified = summary["aig_sha256"] in {s["model_aig_sha256"] for s in ssum["constant_sources"]}
        netlists.append({"name": name, "netlist_dir": str(ndir), "netlist_summary_sha256": digest(ndir / "summary.json"),
                         "netlist_sha256": nsum["netlist_sha256"], "cell_area": nsum["cell_area"], "cells": nsum["cells"],
                         "substitute_design_sha256": ssum["output_design_sha256"],
                         "constant_sources": [{"gap": s["gap"], "model_aig_sha256": s["model_aig_sha256"]}
                                              for s in ssum["constant_sources"]],
                         "certified_for_this_platform": certified,
                         "role": "equivalence check" if certified else "negative control"})
    files.insert(0, cell_models(args.yosys, liberty, cell_types, out, args.timeout))
    layout, low = [], 0
    for name, width in reversed(outputs):
        layout.append({"port": name, "lsb": low, "width": width})
        low += width
    base, words = data_image(args.evidence / "data.hex")
    (out / "image.hex").write_text("".join(f"{w:016x}\n" for w in words))
    tb = fill(TESTBENCH, W=len(records), K=low, NV=len(netlists), THRESHOLD=platform_info["admission_threshold"],
              CMASK=hex_vector(mask), CVAL=hex_vector(value), IMG_BASE=f"{base:x}", IMG_WORDS=len(words),
              INSTANCES="".join(fill(INSTANCE, I=i, NAME=v["name"]) for i, v in enumerate(netlists)),
              CHECKS="".join(fill(CHECK, I=i) for i in range(len(netlists))))
    (out / "tb.sv").write_text(tb)
    files.append(out / "tb.sv")

    env = dict(os.environ, PATH=f"{bin_dir}:/usr/bin:/bin")
    version = subprocess.run([args.verilator, "--version"], env=env, capture_output=True, text=True, check=True).stdout.strip()
    argv = [args.verilator, "--binary", "-j", str(args.jobs), "--x-assign", args.x_assign, "--x-initial", "unique",
            "-Wno-fatal", "-Wno-lint", "-Wno-style", "-Wno-MULTIDRIVEN", "--top-module", "tb",
            "-Mdir", str(out / "obj"), "-o", "simv"] + [str(f) for f in files]
    start = time.time()
    with (out / "build.log").open("w") as log:
        build = subprocess.run(argv, env=env, stdout=log, stderr=subprocess.STDOUT, timeout=args.timeout)
    record = {
        "status": "running", "scope": __doc__.strip().splitlines()[0],
        "model": str(model), "model_aig_sha256": summary["aig_sha256"], "gap": summary["instruction_acceptance_gap"],
        "reach": str(args.reach.resolve()), "constants_sha256": digest(args.reach / "constants.json"),
        "checked_constant_bits": sum(mask), "design_sha256": summary["design_sha256"],
        "evidence": str(args.evidence.resolve()), "data_image_sha256": digest(args.evidence / "data.hex"),
        "netlists": netlists, "liberty_sha256": digest(liberty), "cell_model_types": sorted(cell_types),
        "core_output_bits": low, "core_outputs": layout, "initial_state": "zero (harness registers: shared random)",
        "verilator": version, "x_assign": args.x_assign,
        "build": {"argv": argv, "returncode": build.returncode, "seconds": round(time.time() - start, 1),
                  "log_sha256": digest(out / "build.log")},
        "sources_sha256": {f.name: digest(f) for f in files + [out / "image.hex"]},
        "script_sha256": digest(Path(__file__)),
    }
    (out / "summary.json").write_text(json.dumps(record, indent=2) + "\n")
    if build.returncode != 0:
        raise RuntimeError("Verilator build failed; see build.log")

    expected_stores = [((int(r["time"]) - 1) // 2, int(r["data_store_addr_o"]), int(r["data_store_wdata_o"]),
                        int(r["data_store_be_o"])) for r in csv.DictReader((args.evidence / "accepted_stores.csv").open())]
    runs = [{"seed": s + 1, "image": False, "cycles": args.cycles,
             "reset_period": args.reset_periods[s % len(args.reset_periods)]} for s in range(args.seeds)]
    runs += [{"seed": 1001 + s, "image": True, "cycles": expected_stores[-1][0] + 1000, "reset_period": 0}
             for s in range(args.image_seeds)]

    def execute(run: dict) -> dict:
        rng = random.Random(run["seed"])
        plus = [f"+pinit_{n}={rng.getrandbits(w):x}" for n, w in platform_info["registers"]]
        tag = f"{'image' if run['image'] else 'random'}_{run['seed']}"
        argv = [str(out / "obj/simv"), f"+verilator+seed+{run['seed']}", "+verilator+rand+reset+0",
                f"+cycles={run['cycles']}", f"+reset_period={run['reset_period']}", f"+image={int(run['image'])}"]
        if run["image"]:
            argv += [f"+image_file={out / 'image.hex'}", f"+store_log={out / (tag + '.stores.csv')}"]
        t0 = time.time()
        proc = subprocess.run(argv + plus, env=env, capture_output=True, text=True, timeout=args.timeout)
        (out / f"{tag}.log").write_text(proc.stdout + proc.stderr)
        result = parse_result(proc.stdout)
        result.update(run, returncode=proc.returncode, seconds=round(time.time() - t0, 1),
                      log_sha256=digest(out / f"{tag}.log"))
        for b in result["bits"]:
            port = next(p for p in layout if p["lsb"] <= b["index"] < p["lsb"] + p["width"])
            b["name"] = f"{port['port']}[{b['index'] - port['lsb']}]"
        if run["image"]:
            got = [tuple(int(x) for x in line.split(",")) for line in
                   (out / f"{tag}.stores.csv").read_text().splitlines()]
            result["image_stores"] = {
                "recorded": len(expected_stores), "simulated": len(got),
                "values_match": [g[1:] for g in got] == [e[1:] for e in expected_stores],
                "cycle_shifts": sorted({e[0] - g[0] for e, g in zip(expected_stores, got)}),
                "store_log_sha256": digest(out / f"{tag}.stores.csv")}
        return result

    with concurrent.futures.ThreadPoolExecutor(max_workers=min(len(runs), args.jobs)) as pool:
        results = list(pool.map(execute, runs))
    failures = []
    for r in results:
        where = f"seed {r['seed']}"
        if r["returncode"] != 0 or "digest" not in r or r.get("simulated_cycles") != r["cycles"] \
                or r.get("image_mode") != int(r["image"]) or r.get("reset_period_arg") != r["reset_period"]:
            failures.append(f"{where}: simulation did not finish")
            continue
        for key in ("const_fail", "prop_fail", "service_fail"):
            if r[key]["cycles"]:
                failures.append(f"{where}: {key} at cycle {r[key]['first']}")
        for i, v in enumerate(netlists):
            if v["certified_for_this_platform"] and r["mism"][i]["cycles"]:
                failures.append(f"{where}: {v['name']} differs from the original at cycle {r['mism'][i]['first']}")
        if r["fetches"] == 0 or r["stores"] == 0:
            failures.append(f"{where}: no activity")
        if r["image"]:
            st = r["image_stores"]
            if not st["values_match"] or len(st["cycle_shifts"]) != 1:
                failures.append(f"{where}: stores differ from the recorded RTL simulation")
        elif r["reset_period"] and not r["rereset_events"]:
            failures.append(f"{where}: no re-reset occurred")
    controls = {}
    for i, v in enumerate(netlists):
        if not v["certified_for_this_platform"]:
            diverged = [r for r in results if r["mism"][i]["cycles"]]
            controls[v["name"]] = {"runs": len(results), "diverged_runs": len(diverged),
                                   "first_divergence_cycles": [r["mism"][i]["first"] for r in diverged][:8]}
    record.update(
        status="passed" if not failures else "failed", failures=failures, runs=results,
        totals={"runs": len(results), "cycles": sum(r["cycles"] for r in results),
                "rereset_events": sum(r["rereset_events"] for r in results),
                "alu_rs_admissions_by_row": {k: sum(r["adm"][k] for r in results) for k in range(8)},
                "constant_violation_cycles": sum(r["const_fail"]["cycles"] for r in results),
                "admission_property_violation_cycles": sum(r["prop_fail"]["cycles"] for r in results),
                "service_assertion_violation_cycles": sum(r["service_fail"]["cycles"] for r in results),
                "equivalence_mismatch_cycles": {v["name"]: sum(r["mism"][i]["cycles"] for r in results)
                                                for i, v in enumerate(netlists)},
                "distinct_trace_digests": len({r["digest"] for r in results})},
        negative_controls=controls)
    (out / "summary.json").write_text(json.dumps(record, indent=2) + "\n")
    print(json.dumps({k: record[k] for k in ("status", "gap", "failures", "totals", "negative_controls")}, indent=1))
    return 0 if not failures else 1


if __name__ == "__main__":
    raise SystemExit(main())
